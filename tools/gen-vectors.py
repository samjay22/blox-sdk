#!/usr/bin/env python3
"""Project checked-in JSON vectors into portable Luau without runtime filesystem dependencies."""
from __future__ import annotations
import argparse
import json
import subprocess
from pathlib import Path
from typing import Any
ROOT=Path(__file__).resolve().parents[1]


def literal(value: Any) -> str:
    """Preserve null/array identity and compact repeated large strings for analyzer friendliness."""
    if value is None:return 'Json.null'
    if isinstance(value,bool):return str(value).lower()
    if isinstance(value,str):
        if len(value)>100 and value==value[0]*len(value): return f'string.rep({json.dumps(value[0],ensure_ascii=False)},{len(value)})'
        return json.dumps(value,ensure_ascii=False)
    if isinstance(value,(int,float)):return repr(value)
    if isinstance(value,list):return 'Json.array({'+','.join(literal(v) for v in value)+'} :: {any})'
    if isinstance(value,dict):return 'Json.object({'+','.join('['+literal(k)+']='+literal(v) for k,v in sorted(value.items()))+'} :: any)'
    raise TypeError(type(value))


def main() -> None:
    """Write or check a byte-stable fixture projection; JSON remains the only vector source."""
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    data={p.stem:json.loads(p.read_text()) for p in sorted((ROOT/'tests/vectors').glob('*.json'))}
    text='--!strict\n-- Generated by tools/gen-vectors.py from tests/vectors/*.json.\nlocal Json = require("../src/Core/Json")\nlocal data: any = '+literal(data)+'\nreturn data\n'
    for _ in range(4):
        formatted=subprocess.run(['stylua','--stdin-filepath','tests/FixtureVectors.luau','-'],input=text,capture_output=True,text=True,check=True).stdout
        if formatted==text:break
        text=formatted
    path=ROOT/'tests/FixtureVectors.luau'
    if args.check: assert path.read_text()==text,'Shared vector projection drift'
    else:path.write_text(text)
    print(f'{"Verified" if args.check else "Projected"} shared JSON vectors for portable Luau and Roblox tests')

if __name__=='__main__':main()
