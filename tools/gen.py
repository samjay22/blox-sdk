#!/usr/bin/env python3
"""Deterministically generate Luau endpoints, DTOs, schemas and reference docs offline."""
from __future__ import annotations
import argparse
import json
import re
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SERVICES = {'auth':'Auth','matchmaking':'Matchmaking','party':'Party','codes':'Codes','audit':'Audit','leaderboards':'Leaderboards','fields':'Fields','platform':'Platform'}
GATEWAY_URL = 'https://lb1.blox-api.com'
# The gateway strips these prefixes before forwarding the unchanged controller path.
SERVICE_PREFIXES = {
    'auth': '/auth-service',
    'matchmaking': '/matchmaking-service', 'party': '/party-service',
    'codes': '/code-service', 'audit': '/audit-service',
    'leaderboards': '/leaderboard-service',
    'fields': '/fields-service', 'platform': '/platform-service',
}


def split_generic(text: str) -> list[str]:
    """Split comma-separated Java type arguments at the outermost level."""
    depth, start, result = 0, 0, []
    for i, c in enumerate(text):
        if c == '<': depth += 1
        elif c == '>': depth -= 1
        elif c == ',' and depth == 0: result.append(text[start:i].strip()); start=i+1
    result.append(text[start:].strip())
    return result


def lua(value: object) -> str:
    """Serialize immutable declarative values as deterministic Luau literals."""
    if value is None: return 'nil'
    if value is True: return 'true'
    if value is False: return 'false'
    if isinstance(value,(int,float)): return str(value)
    if isinstance(value,str): return json.dumps(value,ensure_ascii=True)
    if isinstance(value,list): return '{'+','.join(lua(v) for v in value)+'}'
    if isinstance(value,dict):
        rendered='{'+','.join('['+lua(k)+']='+lua(v) for k,v in sorted(value.items()) if v is not None)+'}'
        return '('+rendered+' :: Core.Schema)' if isinstance(value.get('kind'), str) else rendered
    raise TypeError(type(value))


def schema(java: str) -> dict:
    """Translate Java wire types to a small recursive validation language."""
    java=java.strip()
    if '|' in java: return {'kind':'union','items':[schema(x) for x in java.split('|')]}
    if java.startswith('Fields.'):
        return {'kind':'fields','name':java[7:]}
    if java in ('String','UUID','Instant','LocalDateTime','LocalDate'): return {'kind':'string'}
    if java in ('boolean','Boolean'): return {'kind':'boolean'}
    if java in ('long','Long','int','Integer','Double','double','Float','float'): return {'kind':'number'}
    if java=='BigDecimal': return {'kind':'decimal'}
    if java.startswith('CursorPage<'): return {'kind':'cursorPage','item':schema(java[11:-1])}
    if java=='Void': return {'kind':'nil'}
    if java in ('JsonNode','Object','?'): return {'kind':'json'}
    if java.startswith('List<'): return {'kind':'array','item':schema(java[5:-1])}
    if java.startswith('Map<'): return {'kind':'map','item':schema(split_generic(java[4:-1])[1])}
    if java.startswith('Page<'): return {'kind':'page','item':schema(java[5:-1])}
    if java.endswith('.Status'): return {'kind':'string'}
    return {'kind':'ref','name':java.split('.')[-1]}


def typename(s: dict) -> str:
    """Render a schema node as a strict Luau type."""
    kind=s['kind']
    if kind in ('string','number','boolean'): return kind
    if kind=='decimal': return '(number | string)'
    if kind=='cursorPage': return 'CursorPage<'+typename(s['item'])+'>'
    if kind=='nil': return 'nil'
    if kind=='json': return 'Core.Json'
    if kind=='fields': return 'FieldTypes.'+s['name']
    if kind=='array': return '{'+typename(s['item'])+'}'
    if kind=='map': return '{[string]: '+typename(s['item'])+'}'
    if kind=='page': return 'Page<'+typename(s['item'])+'>'
    if kind=='ref': return s['name']
    if kind=='union': return '('+' | '.join(typename(x) for x in s['items'])+')'
    raise ValueError(kind)


def generate(doc: dict) -> dict[Path,str]:
    """Generate all derived artifacts; never consult source repositories or the network."""
    output={}
    assert set(SERVICE_PREFIXES) == set(SERVICES), 'Missing service routing'
    assert {e['service'] for e in doc['endpoints']} == set(SERVICES), 'Unknown or missing service'
    output[ROOT/'src/Core/Routing.luau'] = (
        '--!strict\n-- Generated by tools/gen.py; edit its gateway routing declarations.\n'
        'local prefixes: {[string]: string} = table.freeze('+lua(SERVICE_PREFIXES)+')\n'
        'return table.freeze({gatewayUrl='+lua(GATEWAY_URL)+', prefixes=prefixes})\n'
    )
    runtime_schemas={}
    endpoint_literal={}
    for svc, title in SERVICES.items():
        endpoints=[e for e in doc['endpoints'] if e['service']==svc]
        definitions=doc['types'][svc]
        needed=set()
        def visit(s: dict) -> None:
            """Collect referenced definitions transitively and reject unknown contract types."""
            if s['kind']=='ref':
                n=s['name']
                if n in needed:return
                needed.add(n)
                if n not in definitions: raise ValueError(f'{svc}: missing DTO {n}')
                d=definitions[n]
                if d.get('parent'): visit({'kind':'ref','name':d['parent']})
                for f in d.get('fields',{}).values():visit(schema(f['java']))
            if 'item' in s:visit(s['item'])
            for item in s.get('items',[]):visit(item)
        for e in endpoints:
            visit(schema(e['responseJava']))
            if e['bodyType']:visit(schema(e['bodyType']))
        lines=['--!strict','-- Generated by tools/gen.py. Edit spec/endpoints.json, not this file.','local Core = require("./Core")','export type Page<T> = { content: {T}, number: number, size: number, totalElements: number, totalPages: number, first: boolean, last: boolean, empty: boolean?, numberOfElements: number?, pageable: Core.Json?, sort: Core.Json? }']
        if svc in ('fields','codes'): lines.insert(3, 'local FieldTypes = require("../Fields/Types")')
        lines.append('export type CursorPage<T> = {items: {T}, nextCursor: (string | Core.Null)?}')
        schemas={}
        for name in sorted(needed):
            d=definitions[name]
            if 'enum' in d:
                lines.append('export type '+name+' = '+' | '.join(lua(v) for v in d['enum']))
                schemas[name]={'kind':'enum','values':d['enum']};continue
            fields={}
            if d.get('parent'): fields.update(definitions[d['parent']]['fields'])
            fields.update(d['fields'])
            schemas[name]={'kind':'object','fields':{}}
            pieces=[]
            for n,f in sorted(fields.items()):
                s=schema(f['java']); typ=typename(s)
                if f.get('nullable'):
                    typ='('+typ+' | Core.Null)'; s={'kind':'nullable','item':s}
                if svc=='auth' and name=='ServiceAccountPatchRequest' and n in ('description','expiresAt'):
                    typ='('+typ+' | Core.Null)'; s={'kind':'nullable','item':s}
                if n == 'entryId' and svc in ('fields','codes') and name not in ('GeneratorPick','RotationClaimInput','RotationClaimResult','RotationStock'):
                    typ='(string | Core.Null)'; s={'kind':'nullable','item':{'kind':'string'}}
                if svc=='fields' and name=='BoardActualSettings' and n=='maxDeltaPerSubmit':
                    typ='(number | Core.Null)'; s={'kind':'nullable','item':{'kind':'number'}}
                if not f['required']:typ='('+typ+')?'
                if n == 'nextCursor': typ='(string | Core.Null)?'; s={'kind':'nullable','item':s}
                # JSON keys can be language keywords (schedule UTC window "end").
                field_name = '['+lua(n)+']' if n in ('end','function','local','if','then','else','repeat','until','while','for','do','return','break','in','not','and','or','nil','true','false') else n
                pieces.append(field_name+': '+typ)
                schemas[name]['fields'][n]={'schema':s,'required':f['required'],'notBlank':f.get('notBlank',False)}
            if svc == 'matchmaking' and name == 'MatchmakingCriteriaDTO':
                lines.append('--- fieldName accepts any computed Fields ID, including namespaced IDs such as Stats.Elo (max 200 characters).')
            lines.append('export type '+name+' = {'+', '.join(pieces)+'}')
        for e in endpoints:
            cap=e['name'][0].upper()+e['name'][1:]
            request_type=cap+'Call'
            response_type=e['responseType']
            direct=bool(e['bodyType'] and not e['pathParams'] and not e['queryParams'] and not e.get('idempotencyHeader'))
            e['requestType']=request_type
            e['bodyDirect']=direct
            if direct: req=typename(schema(e['bodyType']))
            else:
                groups=[]
                if e.get('idempotencyHeader'): groups.append('idempotencyKey: string?')
                if e.get('conditional'): groups.append('etag: string?')
                for which in ('path','query'):
                    params=e[which+'Params']
                    if not params:continue
                    fields=[]
                    for p in params:
                        t=p.get('luauType') or ('(string | number)' if p['type']=='id' else p['type'])
                        fields.append(p['name']+': '+t+('?' if not p['required'] or p['name'] in ('universeId','robloxUniverseId') else ''))
                    optional=not any(p['required'] and p['name'] not in ('universeId','robloxUniverseId') for p in params)
                    groups.append(which+': {'+', '.join(fields)+'}'+('?' if optional else ''))
                if e['bodyType']:groups.append('body: '+typename(schema(e['bodyType']))+('?' if not e['bodyRequired'] else ''))
                req='{'+', '.join(groups)+'}'
            lines.append('export type '+request_type+' = '+req)
            lines.append('export type '+response_type+' = '+typename(schema(e['responseJava'])))
            runtime_schemas[e['id']]={'body':schema(e['bodyType']) if e['bodyType'] else None,'response':schema(e['responseJava']),'service':svc}
            lit={k:e[k] for k in ('id','method','path','service','serviceName','minimumLevel','requiredRole','authKinds','idempotent','retryable','cacheable','responseType','responseFormat','pathParams','queryParams','bodyType','bodyRequired')}
            for k in ('idempotencyField','idempotencyItems','conditional','optionalKey','idempotencyHeader','requestFormat','responseContentType'): lit[k]=e.get(k)
            lit['segments']=re.split(r'\{([^}]+)\}',e['path'])
            endpoint_literal[e['id']]=lit
        lines.append('return {}')
        output[ROOT/f'src/Types/{title}.luau']='\n'.join(lines)+'\n'
        runtime_schemas[svc]=schemas
        lines=['--!strict','-- Generated by tools/gen.py. Edit spec/endpoints.json, not this file.','local Core = require("../Types/Core")',f'local Types = require("../Types/{title}")','local Endpoints = require("../Core/Endpoints")','local Service = {}','Service.__index = Service','export type Service = typeof(setmetatable({} :: { _invoke: Core.Invoke, _universe: (string | number)? }, Service))','--- Bind a typed service facade to the shared pipeline.','function Service.new(invoke: Core.Invoke, universe: (string | number)?): Service','return setmetatable({_invoke=invoke, _universe=universe}, Service)','end']
        if svc == 'matchmaking':
            lines.insert(2, '-- Queue metadata is enriched server-side from FieldsService; callers need Fields READ access.')
        if svc in ('fields','codes'):
            lines = [line.replace('_universe: (string | number)? }', '_universe: (string | number)?, _fields: Helpers.State? }').replace('universe: (string | number)?): Service', 'universe: (string | number)?, helpers: Helpers.State?): Service').replace('_universe=universe}', '_universe=universe, _fields=helpers}') for line in lines]
        if svc == 'codes':
            lines[3:3] = ['local Helpers = require("../Fields/Client")', 'local Award = require("../Codes/Award")']
            lines += ['--- Create a typed subject-free award builder over the loaded universe schema.',
                      'function Service.Award(self: Service, universeId: string | number): Award.Builder return Award.new(assert(self._fields, "Fields helpers unavailable"), universeId) end']
        if svc == 'fields':
            lines[3:3] = ['local Helpers = require("../Fields/Client")', 'local Schema = require("../Fields/Schema")', 'local Transaction = require("../Fields/Transaction")', 'local Profile = require("../Fields/Profile")', 'local OpBuilder = require("../Fields/OpBuilder")']
            for module in ('Bulk','Schedules','Jobs','Health','Rotations','Generators'):
                lines.insert(3, 'local '+module+' = require("../Fields/'+module+'")')
                helper_type = 'Builder' if module == 'Bulk' else 'Client'
                lines.extend([
                    '--- Bind '+module+' helpers to an explicit universe; '+('server authorization remains authoritative.' if module in ('Rotations','Generators') else 'control-plane mutations require a server ADMIN key.'),
                    f'function Service.{module}(self: Service, universeId: string | number): {module}.{helper_type} return {module}.new(assert(self._fields, "Fields helpers unavailable"), universeId) end',
                ])
            lines += [
                '--- Build a subject-free list for read-only static validation.',
                'function Service.Operations(self: Service, universeId: string | number): OpBuilder.Builder return Helpers.operations(assert(self._fields, "Fields helpers unavailable"), universeId) end',
                '--- Resolve the lazy schema cache for an explicit universe.',
                'function Service.Schema(self: Service, universeId: string | number): Schema.Schema return Helpers.schema(assert(self._fields, "Fields helpers unavailable"), universeId) end',
                '--- Create a validated player transaction; load Schema first or use LoadProfile.',
                'function Service.Transaction(self: Service, universeId: string | number, userId: number): Transaction.Transaction return Helpers.transaction(assert(self._fields, "Fields helpers unavailable"), universeId, userId) end',
                '--- Create an atomic multi-subject builder; select subjects with Subject(id).',
                'function Service.MultiTransaction(self: Service, universeId: string | number): Transaction.Transaction return Helpers.transaction(assert(self._fields, "Fields helpers unavailable"), universeId, nil) end',
                '--- Fetch a typed player document with owned presence/refresh lifecycle.',
                'function Service.LoadProfile(self: Service, universeId: string | number, userId: number): Core.Result<Profile.Profile> return Helpers.loadProfile(assert(self._fields, "Fields helpers unavailable"), universeId, userId) end',
                '--- Submit a trusted receipt; the server deduplicates purchaseId across calls and restarts.',
                'function Service.ProcessReceipt(self: Service, universeId: string | number, receipt: Types.ReceiptInput, opts: Core.CallOptions?): Core.Result<Types.ReceiptResult> return self:purchase({path={universeId=universeId},body=receipt},opts) end',
            ]
        if any('cursor' == p['name'] for e in endpoints for p in e['queryParams']):
            lines.insert(5, 'local Pagination = require("../Core/Pagination")')
            lines.insert(6, 'local Idempotency = require("../Core/Idempotency")')
        for e in endpoints:
            optional=not e['bodyRequired'] and not any(p['required'] and p['name'] not in ('universeId','robloxUniverseId') for p in e['pathParams']+e['queryParams'])
            rt='Types.'+e['requestType']+('?' if optional else '')
            req='{body=req}' if e['bodyDirect'] else '(req or {})' if optional else 'req'
            body = [f'return self._invoke(Endpoints[{lua(e["id"])}], {req}, opts, self._universe)']
            if e['id'] == 'fields.validateOps':
                body = ['local scope = (req.path and req.path.universeId) or self._universe',
                        'return Helpers.validateOps(assert(self._fields, "Fields helpers unavailable"), scope :: string | number, req.body, opts)']
            if e['id'] in ('codes.createCode','codes.updateCode','codes.bulkCreateCodes'):
                helper = {'createCode':'create', 'updateCode':'update', 'bulkCreateCodes':'bulk'}[e['name']]
                body = [f'local prepared = Award.{helper}(assert(self._fields, "Fields helpers unavailable"), req, self._universe)',
                        'if not prepared.ok then return prepared end',
                        f'return self._invoke(Endpoints[{lua(e["id"])}], '+ ('{body=prepared.value}' if e['bodyDirect'] else 'prepared.value') + ', opts, self._universe)']
            lines.extend([f'--- {e["method"]} {SERVICE_PREFIXES[svc]}{e["path"]} via gateway; access: {e["requiredRole"] or e["minimumLevel"] or "public/authenticated"}.',f'function Service.{e["name"]}(self: Service, req: {rt}, opts: Core.CallOptions?): Core.Result<Types.{e["responseType"]}>', *body, 'end'])
            if any(p['name']=='cursor' for p in e['queryParams']):
                lines.extend([f'--- Lazily iterate cursor pages, preserving filters and surfacing errors.', f'function Service.{e["name"]}Pages(self: Service, req: {rt}, opts: Core.CallOptions?, maximum: number?): () -> Core.Result<Types.{e["responseType"]}>?', f'local request: Types.{e["requestType"]} = Idempotency.copy(req or {{}})', 'local query = table.clone(request.query or {})', 'request.query = query', f'return Pagination.cursor(function(cursor: string?): Core.Result<Types.{e["responseType"]}>', 'query.cursor = cursor', f'return self.{e["name"]}(self, request, opts)', f'end, function(page: Types.{e["responseType"]}): (string | Core.Null)? return page.nextCursor end, maximum, query.cursor)', 'end'])
        lines.append('return table.freeze(Service)')
        output[ROOT/f'src/Services/{title}.luau']='\n'.join(lines)+'\n'
    output[ROOT/'src/Core/Endpoints.luau']='--!strict\n-- Generated endpoint metadata, recursively frozen.\nlocal Core = require("../Types/Core")\nlocal Cache = require("./Cache")\nlocal endpoints: {[string]: Core.Endpoint} = '+lua(endpoint_literal)+'\nreturn Cache.freeze(endpoints) :: {[string]: Core.Endpoint}\n'
    definitions_literal={k:v for k,v in runtime_schemas.items() if k in SERVICES}
    endpoints_schema={k:v for k,v in runtime_schemas.items() if k not in SERVICES}
    output[ROOT/'src/Core/Schemas.luau']='--!strict\n-- Generated validation schemas.\nlocal Core = require("../Types/Core")\nlocal Cache = require("./Cache")\nlocal definitions: {[string]: {[string]: Core.Schema}} = '+lua(definitions_literal)+'\nlocal endpoints: {[string]: Core.EndpointSchema} = '+lua(endpoints_schema)+'\nreturn Cache.freeze({definitions=definitions,endpoints=endpoints}) :: {definitions: {[string]: {[string]: Core.Schema}}, endpoints: {[string]: Core.EndpointSchema}}\n'

    rows=['# Endpoint reference','',f'{len(doc["endpoints"])} endpoints. `routes.json` coverage is checked independently.','', 'Request shapes are exported in `src/Types`. Body-only endpoints accept the DTO directly; mixed endpoints use `{path=..., query=..., body=...}`. Statuses below are controller success/branch statuses, not exhaustive domain errors.']
    rows[4:4] = [
        f'Default gateway: `{GATEWAY_URL}`. Override once with `gatewayUrl`.', '',
        '**lb1 requires `Gateway` permission in addition to the target service permission. `bsa_` service-account keys are universe-bound.**', '',
        '| Service | Gateway stripPrefix |', '|---|---|',
        *[f'| `{svc}` | `{prefix}` |' for svc, prefix in SERVICE_PREFIXES.items()], '',
        'Paths below are backend-relative: wire URL = gateway + service prefix + path. '
        'Game configuration lives in Fields. Platform preserves its domain prefix on direct hosts. '
        'An explicit `services = { fields = { baseUrl = "https://direct.example" } }` bypasses the gateway '
        'and prefix for that service only. See [routing configuration](../README.md#gateway-routing).', '',
    ]
    rows.extend(['', '**ADMIN endpoints are server/admin-key usage only.** Keep credentials in trusted server storage; never expose control-plane requests to untrusted game clients. Fields durable jobs, migrations, bulk/import/export, schedule controls, and alerts require FieldsService ADMIN, including previews and downloads. Fields health summary and schedule run history require READ.', '', 'Fields imports accept raw NDJSON in `body` with `query={reason=...,dryRun=...}` and top-level `idempotencyKey` for apply. Downloads return raw NDJSON strings, not decoded JSON.'])
    rows.extend(['', '**Auth IDENTITY means identity authentication, not an automatic capability grant.** Org ADMIN/OWNER gates, delegation caps, quotas and last-owner checks remain server-enforced. Scoped JWTs and machine keys cannot manage orgs/keys. Humans/tools use identity login then `client:scoped(id)` for downstream access; game servers should use `bsa_` keys. See [Auth role templates and error codes](AUTH.md).'])
    rows.extend(['', '| Method | Path | SDK method | Service level / role | Success / branch | Retry by default | Cache eligible |','|---|---|---|---|---|---|---|'])
    for e in doc['endpoints']:
        retry = 'keyed apply / dry-run' if e.get('idempotencyHeader') else 'keyed' if e.get('idempotencyField') else 'yes' if e['retryable'] else 'no'
        rows.append('| '+ ' | '.join([e['method'],'`'+e['path']+'`','`'+e['id']+'`',e['requiredRole'] or e['minimumLevel'] or 'public / authenticated',', '.join(map(str,e['statuses'])),retry,'yes' if e['cacheable'] else 'no'])+' |')
    output[ROOT/'docs/ENDPOINTS.md']='\n'.join(rows)+'\n'
    from coverage_report import render
    output[ROOT/'SDK_COVERAGE.md'] = render(doc, SERVICE_PREFIXES)
    provenance=json.loads((ROOT/'spec/provenance.json').read_text())
    prefixes=('srv/src-mm/', 'srv/src-roblox-code-service/', 'srv/src-gas/', 'svc/')
    provenance['files']={k:v for k,v in provenance['files'].items() if not k.startswith(prefixes)}
    provenance['files'].update(doc.get('sourceHashes', {}))
    output[ROOT/'spec/provenance.json']=json.dumps(provenance,indent=2,sort_keys=True)+'\n'
    return output


def main() -> None:
    """Write formatted generated sources, or compare them byte-for-byte in --check mode."""
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');parser.add_argument('--refresh-sources',action='store_true');args=parser.parse_args()
    doc=json.loads((ROOT/'spec/endpoints.json').read_text())
    if args.refresh_sources:
        if args.check: parser.error('--check and --refresh-sources are mutually exclusive')
        from service_contracts import refresh, SOURCES
        doc=refresh(doc)
        (ROOT/'spec/endpoints.json').write_text(json.dumps(doc,indent=2,sort_keys=True)+'\n')
        routes=json.loads((ROOT/'routes.json').read_text())
        routes=[r for r in routes if r['svc'] != 'config' and {'mm':'matchmaking','code':'codes'}.get(r['svc'],r['svc']) not in SOURCES]
        routes.extend({'svc':e['service'],'method':e['method'],'path':e['path']} for e in doc['endpoints'] if e['service'] in SOURCES)
        (ROOT/'routes.json').write_text(json.dumps(routes,indent=2)+'\n')
    outputs=generate(doc)
    drift=[]
    for path,text in outputs.items():
        if path.suffix=='.luau':
            for _ in range(4):
                formatted=subprocess.run(['stylua','--stdin-filepath',str(path),'-'],input=text,text=True,capture_output=True,check=True,cwd=ROOT).stdout
                if formatted==text: break
                text=formatted
        if args.check:
            if not path.exists() or path.read_text()!=text:drift.append(str(path.relative_to(ROOT)))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    if drift:raise SystemExit('Generated drift: '+', '.join(drift))
    print(('Verified' if args.check else 'Generated')+f' {len(outputs)} artifacts / {len(doc["endpoints"])} endpoints')
if __name__=='__main__':main()
