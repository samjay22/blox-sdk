"""Offline, stdlib-only schema-to-Luau domain types and statically typed accessors."""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path
from typing import Any


def quote(value: str) -> str:
    """Quote a Luau string using JSON-compatible escapes."""
    return json.dumps(value, ensure_ascii=False)


def alias(identifier: str) -> str:
    """Use the server's reversible escaping; collisions are impossible."""
    return 'Field_' + identifier.replace('_', '_U_').replace('.', '_D_')


def typ(tree: dict[str, Any]) -> str:
    """Render client-domain sets/maps and explicit-null unions without erasing static types."""
    kind = tree['kind']
    if kind in ('int', 'number'): return 'number'
    if kind == 'bool': return 'boolean'
    if kind == 'string': return 'string'
    if kind == 'enum': return ' | '.join(quote(v) for v in tree['values'])
    if kind == 'nullable': return '(' + typ(tree['of']) + ' | Core.Null)'
    if kind == 'list': return '{' + typ(tree['item']) + '}'
    if kind == 'set':
        if tree['item']['kind']=='enum': return '{'+', '.join('['+quote(v)+']: true?' for v in tree['item']['values'])+'}'
        return '{[' + typ(tree['item']) + ']: true}'
    if kind == 'map':
        if tree['key']['kind']=='enum': return '{'+', '.join('['+quote(v)+']: ('+typ(tree['value'])+')?' for v in tree['key']['values'])+'}'
        return '{[' + typ(tree['key']) + ']: ' + typ(tree['value']) + '}'
    if kind == 'object':
        return '{' + ', '.join('['+quote(k)+']: '+ ('('+typ(v['type'])+')?' if v.get('optional') else typ(v['type'])) for k,v in sorted(tree['members'].items())) + '}'
    raise ValueError('Unknown TypeExpr kind')


def literal(value: Any) -> str:
    """Render JSON schema metadata, preserving null defaults and empty arrays."""
    if value is None: return 'Json.null'
    if isinstance(value, bool): return str(value).lower()
    if isinstance(value, str): return quote(value)
    if isinstance(value, (int,float)): return repr(value)
    if isinstance(value, list): return 'Json.array({'+','.join(literal(v) for v in value)+'})'
    if isinstance(value, dict): return '{'+','.join('['+quote(k)+']='+literal(v) for k,v in sorted(value.items()))+'}'
    raise ValueError('Non-JSON schema value')


def nested(tree: dict[str, Any]) -> str:
    """Render a dotted namespace tree into a nested static document type."""
    return '{'+', '.join('['+quote(k)+']: '+(nested(v) if isinstance(v,dict) else v) for k,v in sorted(tree.items()))+'}'


def insert(tree: dict[str, Any], identifier: str, value: str) -> None:
    """Reject duplicate and dotted-prefix collisions before building namespaces."""
    parts=identifier.split('.')
    for part in parts[:-1]:
        node=tree.setdefault(part,{})
        if not isinstance(node,dict): raise ValueError('Field prefix collision')
        tree=node
    if parts[-1] in tree: raise ValueError('Duplicate field or prefix collision')
    tree[parts[-1]]=value


def generate(schema: dict[str, Any], sdk: str, roblox_root: str | None = None) -> dict[str,str]:
    """Generate deterministic artifacts without consulting backend sources, tools or network."""
    if type(schema.get('schemaVersion')) is not int or schema['schemaVersion']<0: raise ValueError('Invalid schemaVersion')
    universe=schema.get('universeId')
    if type(universe) is int:
        if not 0<universe<=9223372036854775807: raise ValueError('Invalid universeId')
    elif not isinstance(universe,str) or not re.fullmatch(r'[1-9][0-9]{0,18}',universe) or int(universe)>9223372036854775807: raise ValueError('Invalid universeId')
    definitions=sorted(schema['definitions'],key=lambda d:d['id'])
    ids={}; document={}; access={}
    digest=hashlib.sha256(json.dumps(schema,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()).hexdigest()
    header=f'--!strict\n-- Schema universeId={schema["universeId"]} schemaVersion={schema["schemaVersion"]} sha256={digest}\n-- Generated by tools/gen-field-types; do not edit.\n'
    lines=[header, f'local Core = require({quote(sdk+"/Types/Core")})']
    output={}
    imports=[]
    for d in definitions:
        identifier=d['id']
        if len(identifier)>200 or not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{0,63}(\.[A-Za-z][A-Za-z0-9_]{0,63}){0,7}',identifier): raise ValueError('Invalid field ID')
        insert(ids,identifier,identifier)
        computed=bool(d.get('computed'))
        expression={'kind':'nullable','of':{'kind':d['computed']['returns']}} if computed else d['type']
        name=alias(identifier)
        lines.append(f'export type {name} = {typ(expression)}')
        if d.get('status','ACTIVE')!='ACTIVE' or d.get('scope','PLAYER')!='PLAYER': continue
        insert(document,identifier,name)
        insert(access,identifier,'Accessor_'+name)
        imports.append(f'local Accessor_{name} = require("./Accessors/{name}")')
        # Accessor modules live one level below FieldTypes; SDK paths are relative to the output dir.
        local_sdk='../'+sdk if sdk.startswith('.') else sdk
        a=[header, 'local FieldTypes = require("../FieldTypes")',f'local Profile = require({quote(local_sdk+"/Fields/Profile")})']
        if not computed:
            a += [f'local Transaction = require({quote(local_sdk+"/Fields/Transaction")})',f'local Codec = require({quote(local_sdk+"/Fields/WireCodec")})',f'local Json = require({quote(local_sdk+"/Core/Json")})',f'local Types = require({quote(local_sdk+"/Fields/Types")})']
            a.append('local expression: Types.TypeExpr = '+literal(expression))
        a += ['local Accessor = {}',f'--- Read the validated {identifier} client-domain value.',f'function Accessor.get(_self: unknown, profile: Profile.Profile): FieldTypes.{name}']
        if computed:a.append(f' return profile:get({quote(identifier)}) :: any')
        else:a.append(f' return Codec.decode(expression, profile:get({quote(identifier)})) :: FieldTypes.{name}')
        a.append('end')
        if not computed:
            a+=['--- Queue a schema-validated replacement.',f'function Accessor.set(_self: unknown, tx: Transaction.Transaction, value: FieldTypes.{name}): Transaction.Transaction',f' return tx:set({quote(identifier)}, Codec.encode(expression,value))','end',
                '--- Queue a schema-validated reset.',f'function Accessor.reset(_self: unknown, tx: Transaction.Transaction): Transaction.Transaction return tx:reset({quote(identifier)}) end']
            kind=expression['kind']
            if kind in ('int','number'):
                for method in ('add','min','max'):
                    a += [f'--- Queue a numeric {method.lower()} operation.',f'function Accessor.{method}(_self: unknown, tx: Transaction.Transaction, value: number): Transaction.Transaction return tx:{method}({quote(identifier)},value) end']
            if kind in ('list','set'):
                item=expression['item']; item_type=typ(item)
                methods=('append','insert','setAdd','setRemove') if kind=='list' else ('setAdd','setRemove')
                methods=('append','insert') if kind=='list' else methods
                for method in methods:
                    index='index: number, ' if method=='insert' else ''
                    arg='index, ' if method=='insert' else ''
                    a += [f'--- Queue typed {method} items.',f'function Accessor.{method}(_self: unknown, tx: Transaction.Transaction, {index}items: {{{item_type}}}): Transaction.Transaction',f' local wire = Codec.encode({literal({"kind":"list","item":item})},items)',f' return tx:{method}({quote(identifier)},{arg}wire :: any)','end']
                if kind=='list':
                    a += ['--- Remove a zero-based list range.',f'function Accessor.removeAt(_self: unknown, tx: Transaction.Transaction, index: number, count: number?): Transaction.Transaction return tx:removeAt({quote(identifier)},index,count) end',
                          '--- Remove the first typed canonical match.',f'function Accessor.removeValue(_self: unknown, tx: Transaction.Transaction, value: {item_type}): Transaction.Transaction return tx:removeValue({quote(identifier)},Codec.encode({literal(item)},value)) end']
            if kind=='map':
                key_type=typ(expression['key'])
                key='Codec.key(key)' if expression['key']['kind']=='int' else 'key'
                a += ['--- Merge typed map entries.',f'function Accessor.mapPut(_self: unknown, tx: Transaction.Transaction, entries: FieldTypes.{name}): Transaction.Transaction return tx:mapPut({quote(identifier)},Codec.encode(expression,entries) :: any) end',
                      '--- Remove typed keys using canonical wire strings.',f'function Accessor.mapRemove(_self: unknown, tx: Transaction.Transaction, keys: {{{key_type}}}): Transaction.Transaction',f' local wire = {{}}\n for _,key in keys do\n  table.insert(wire,{key})\n end',f' return tx:mapRemove({quote(identifier)},wire)','end']
                if expression['value']['kind'] in ('int','number'):
                    a += ['--- Queue a numeric delta on one typed map key.',f'function Accessor.mapAdd(_self: unknown, tx: Transaction.Transaction, key: {key_type}, delta: number): Transaction.Transaction return tx:mapAdd({quote(identifier)},{key},delta) end']
        # Metadata can be scalar and not need Json; avoid unused imports without hiding warnings.
        if not any('Json.' in line for line in a): a=[line for line in a if not line.startswith('local Json =')]
        if any('Core.' in line for line in a): a.insert(3, f'local Core = require({quote(local_sdk+"/Types/Core")})')
        a.append('return table.freeze(Accessor)')
        a = [line.replace(' return ', '\n return ', 1).removesuffix(' end')+'\nend' if line.startswith('function ') and ' return ' in line else line for line in a]
        output['Accessors/'+name+'.luau']='\n'.join(a)+'\n'
    lines += ['export type FieldId = '+(' | '.join(quote(d['id']) for d in definitions) or 'never'),
              'export type FieldValues = {'+', '.join('['+quote(d['id'])+']: '+alias(d['id']) for d in definitions)+'}',
              'export type PlayerDocument = '+nested(document),'return {}']
    if not any('Core.' in line for line in lines):lines=[line for line in lines if not line.startswith('local Core =')]
    output['FieldTypes.luau']='\n'.join(lines)+'\n'
    def table(tree: dict[str, Any]) -> str:
        """Render the typed accessor namespace without any dynamic indexer."""
        return 'table.freeze({'+','.join('['+quote(k)+']='+ (table(v) if isinstance(v,dict) else v) for k,v in sorted(tree.items()))+'})'
    output['Typed.luau']=header+'\n'.join(imports)+'\nreturn '+table(access)+'\n'
    if roblox_root is not None:
        if not re.fullmatch(r'game(?:\.[A-Za-z_][A-Za-z0-9_]*)+', roblox_root): raise ValueError('Invalid Roblox SDK Instance root')
        for name, source in output.items():
            def project(match: re.Match[str]) -> str:
                """Resolve only generator-owned imports to literal Instance paths, never execute input."""
                target=match[1]
                if target=='../FieldTypes': return 'require(script.Parent.Parent.FieldTypes)'
                if target.startswith('./Accessors/'): return 'require(script.Parent.Accessors.'+target.rsplit('/',1)[1]+')'
                suffix=target.split('/Fields/',1)[-1] if '/Fields/' in target else None
                if suffix is not None:return 'require('+roblox_root+'.Fields.'+suffix+')'
                if target.endswith('/Types/Core'):return 'require('+roblox_root+'.Types.Core)'
                if target.endswith('/Core/Json'):return 'require('+roblox_root+'.Core.Json)'
                raise ValueError('Unexpected generated import')
            output[name]=re.sub(r'require\("([^"\n]+)"\)',project,source)
    return output


def main() -> None:
    """Read a saved GET /schema JSON and write/check deterministic local ModuleScripts."""
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('schema',type=Path);parser.add_argument('--out',type=Path,required=True)
    parser.add_argument('--sdk',default='../src',help='Luau require path to SDK root, relative to output directory')
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--roblox-root',help='SDK ModuleScript expression, e.g. game.ServerScriptService.BloxSDK')
    args=parser.parse_args()
    schema=json.loads(args.schema.read_text())
    files=generate(schema,args.sdk,args.roblox_root)
    expected=set(files)
    for stale in args.out.glob('Accessors/Field_*.luau'):
        relative=str(stale.relative_to(args.out))
        if relative not in expected and '-- Generated by tools/gen-field-types; do not edit.' in stale.read_text():
            if args.check:raise SystemExit('Stale generated accessor: '+relative)
            stale.unlink()
    for relative,text in files.items():
        path=args.out/relative
        if args.check:
            if not path.exists() or path.read_text()!=text: raise SystemExit('Generated field type drift: '+relative)
        else: path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
    print(f'{"Verified" if args.check else "Generated"} {len(files)} field type/accessor modules')

if __name__=='__main__': main()
